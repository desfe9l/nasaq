/**
 * Inline the SVG rasterizer's wasm and Arabic fonts into a TypeScript module.
 *
 * Nitro rewrites `new URL("./resvg.wasm", import.meta.url)` to the serverless
 * chunk directory and does not copy the binary, so a runtime `readFile` 500s
 * in production (`ENOENT … /var/task/_ssr/resvg.wasm`). Emitting the bytes as
 * base64 puts them in the JS module graph, which the server bundle always
 * includes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const FACES = [
  "Tajawal-Regular.ttf",
  "Tajawal-Bold.ttf",
  "NotoNaskhArabic-Regular.ttf",
  "NotoNaskhArabic-Bold.ttf",
];

function b64(rel) {
  return readFileSync(join(root, rel)).toString("base64");
}

export function emitShareRasterAssets() {
  const fonts = FACES.map(
    (name) => `  decode(${JSON.stringify(b64(`src/lib/og/fonts/${name}`))})`,
  ).join(",\n");
  const source = `/* Generated by scripts/emit-share-raster-assets.mjs. Do not edit. */
import { Buffer } from "node:buffer";

function decode(value: string): Uint8Array {
  const bin = Buffer.from(value, "base64");
  return new Uint8Array(bin.buffer, bin.byteOffset, bin.byteLength);
}

export const wasm: Uint8Array = decode(${JSON.stringify(b64("src/lib/og/resvg.wasm"))});

export const fonts: Uint8Array[] = [
${fonts}
];
`;
  const out = join(root, "src/lib/og/share-raster-assets.generated.ts");
  writeFileSync(out, source);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = emitShareRasterAssets();
  console.log(`wrote ${out}`);
}
